#!/bin/bash
# パソコンの状態コマンド - ディスク容量確認

echo "=============================="
echo "  ディスク容量の状態"
echo "=============================="
echo ""

df -h | awk '
NR==1 {
    printf "%-20s %6s %6s %6s %5s %s\n", "ファイルシステム", "合計", "使用済", "空き", "使用%", "マウント先"
    print "--------------------------------------------------------------"
}
NR>1 {
    printf "%-20s %6s %6s %6s %5s %s\n", $1, $2, $3, $4, $5, $6
}
'

echo ""
echo "=============================="
echo "  使用率が高いパーティション (80%以上)"
echo "=============================="
echo ""

HIGH=$(df -h | awk 'NR>1 { gsub(/%/, "", $5); if ($5+0 >= 80) print $0 }')
if [ -z "$HIGH" ]; then
    echo "  警告なし - すべてのパーティションは正常です"
else
    echo "$HIGH" | while read line; do
        echo "  警告: $line"
    done
fi

echo ""
